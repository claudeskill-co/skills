#!/usr/bin/env node
/**
 * Generate the two catalogue files from the plugin tree.
 *
 *   .claude-plugin/marketplace.json   what Claude Code reads
 *   registry.json                     what claudeskill.co reads
 *
 * Both are derived, so they cannot drift apart or from the plugins themselves.
 * Never hand-edit either file.
 *
 *     node scripts/gen-registry.mjs          # write
 *     node scripts/gen-registry.mjs --check  # fail if the committed files are stale
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import {
  ROOT,
  GITHUB_SLUG,
  MARKETPLACE_NAME,
  SITE_URL,
  readPlugins,
  toMarketplaceEntry,
  toRegistryEntry,
} from "./lib/catalog.mjs";

const plugins = readPlugins();

const OWNER = {
  name: "ClaudeSkill",
  email: "hello@claudeskill.co",
  url: SITE_URL,
};

const marketplace = {
  name: MARKETPLACE_NAME,
  owner: OWNER,
  metadata: {
    description: "Installable Claude skills for D2C and ecommerce operators.",
    pluginRoot: "./plugins",
  },
  plugins: plugins.map(toMarketplaceEntry),
};

const registry = {
  $comment: "Generated by scripts/gen-registry.mjs - do not edit by hand.",
  version: 1,
  site: SITE_URL,
  repo: `https://github.com/${GITHUB_SLUG}`,
  marketplace: MARKETPLACE_NAME,
  skills: plugins.map(toRegistryEntry),
};

const targets = [
  [join(ROOT, ".claude-plugin", "marketplace.json"), marketplace],
  [join(ROOT, "registry.json"), registry],
];

const check = process.argv.includes("--check");
let stale = false;

for (const [path, value] of targets) {
  const next = `${JSON.stringify(value, null, 2)}\n`;
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;

  if (current === next) continue;

  if (check) {
    console.error(`stale ${path.replace(`${ROOT}/`, "")} - run: node scripts/gen-registry.mjs`);
    stale = true;
  } else {
    writeFileSync(path, next);
    console.log(`wrote ${path.replace(`${ROOT}/`, "")}`);
  }
}

if (stale) process.exit(1);
if (!check) console.log(`ok    ${plugins.length} plugin(s) in the catalogue`);
